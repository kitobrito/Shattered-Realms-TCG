"""Bundle the level-matched clips into a few files for the game.

  art/sfx/effects.mp3        every short effect, back to back
  art/sfx/voice-<actor>.mp3  one voice actor's greetings / refusals / confirmations / death cries
  art/sfx/amb-*.mp3          ambience loops (kept as their own files)
  src/ui/sfx-sprites.js      where each clip starts and how long it lasts
"""
import json, os, subprocess, sys
import numpy as np

CLIPS = sys.argv[1]            # folder of individual clips (from build_sfx.py)
OUT = '/home/user/sr-ui/art/sfx/'
JS = '/home/user/sr-ui/src/ui/sfx-sprites.js'
SR = 44100
GAP = 0.25


def pcm(path):
    raw = subprocess.run(['ffmpeg', '-v', 'error', '-i', path, '-f', 's16le', '-ac', '1', '-ar', str(SR), '-'],
                         capture_output=True, check=True).stdout
    return np.frombuffer(raw, np.int16)


def write(path, data, br='96k'):
    subprocess.run(['ffmpeg', '-v', 'error', '-y', '-f', 's16le', '-ac', '1', '-ar', str(SR), '-i', '-',
                    '-b:a', br, path], input=data.tobytes(), check=True)


def sprite(names, out_name, br='80k'):
    gap = np.zeros(int(SR * GAP), np.int16)
    parts, table, t = [gap], {}, GAP
    for n in names:
        d = pcm(os.path.join(CLIPS, n + '.mp3'))
        table[n] = [round(t, 3), round(len(d) / SR, 3)]
        parts += [d, gap]
        t += len(d) / SR + GAP
    write(os.path.join(OUT, out_name), np.concatenate(parts), br)
    return table


os.makedirs(OUT, exist_ok=True)
for f in os.listdir(OUT):
    os.remove(os.path.join(OUT, f))
names = sorted(f[:-4] for f in os.listdir(CLIPS) if f.endswith('.mp3'))
effects = [n for n in names if not n.startswith(('v-', 'amb-'))]
actors = sorted({n.split('-')[1] for n in names if n.startswith('v-')})

files = {'effects': 'art/sfx/effects.mp3'}
clips = {n: ['effects', *v] for n, v in sprite(effects, 'effects.mp3').items()}
for a in actors:
    files[f'voice-{a}'] = f'art/sfx/voice-{a}.mp3'
    for n, v in sprite([n for n in names if n.startswith(f'v-{a}-')], f'voice-{a}.mp3', '48k').items():
        clips[n] = [f'voice-{a}', *v]
loops = {}
for n in names:
    if n.startswith('amb-'):
        subprocess.run(['cp', os.path.join(CLIPS, n + '.mp3'), os.path.join(OUT, n + '.mp3')], check=True)
        loops[n[4:]] = f'art/sfx/{n}.mp3'

with open(JS, 'w') as f:
    f.write('// Generated by the sound build (tools/sfx/make_sprites.py): do not edit by hand.\n')
    f.write('// clips: name -> [file, start seconds, length seconds]. Sources: Horror Sounds Vol 3,\n')
    f.write('// Cosmic Horror (Ririsaurus), Robots & Mechs sampler, Planarian BGM monster voices,\n')
    f.write('// the Spells pack and the five-actor voice packs; all free for games.\n')
    f.write('export const SFX_FILES = ' + json.dumps(files, indent=2) + ';\n')
    f.write('export const SFX_CLIPS = ' + json.dumps(clips, separators=(',', ':')) + ';\n')
    f.write('export const AMBIENCE_FILES = ' + json.dumps(loops, indent=2) + ';\n')
total = sum(os.path.getsize(os.path.join(OUT, f)) for f in os.listdir(OUT))
print(json.dumps({'clips': len(clips), 'files': len(os.listdir(OUT)), 'MB': round(total / 1e6, 2)}))
