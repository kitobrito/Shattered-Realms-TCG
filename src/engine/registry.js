// Card database. Cards are plain data; the engine looks them up by id.

const CARDS = new Map();

export function registerCards(list) {
  for (const card of list) CARDS.set(card.id, card);
}

export function getCard(id) {
  const card = CARDS.get(id);
  if (!card) throw new Error(`Unknown card id: ${id}`);
  return card;
}

export function hasCard(id) {
  return CARDS.has(id);
}

export function allCards() {
  return [...CARDS.values()];
}

// Cards created during a game (Gene Splicing Hybrids, Terraform, Hatchery).
// They live in state.customCards so saves and AI clones carry them; this
// registers them so getCard() can resolve their ids.
export function registerCustom(state, card) {
  state.customCards ??= {};
  state.customCards[card.id] = card;
  CARDS.set(card.id, card);
}

export function restoreCustomCards(state) {
  for (const card of Object.values(state.customCards ?? {})) CARDS.set(card.id, card);
}

// Minions that can be generated by random effects (transform, etc.):
// real deck cards with stats, excluding tokens, Hero Spells and unfinished cards.
export function collectibleMinions(filter = () => true) {
  return allCards().filter((c) => c.type === 'minion' && !c.token && !c.heroSpell && !c.pending && !c.custom &&
    c.attack != null && c.health != null && filter(c));
}
